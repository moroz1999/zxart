-- Step 3: normalize the link table to ids -------------------------------------
ALTER TABLE `engine_module_zxrelease_hw_required` ENGINE = InnoDB;

ALTER TABLE `engine_module_zxrelease_hw_required`
    ADD COLUMN `hardwareId` INT UNSIGNED NOT NULL DEFAULT 0 AFTER `elementId`;

UPDATE `engine_module_zxrelease_hw_required` `l`
    JOIN `engine_hardware` `h` ON `h`.`code` = `l`.`value`
SET `l`.`hardwareId` = `h`.`id`;

-- GATE: the next statement must return 0. A non-zero count means some stored
-- code is missing from the seed above; STOP and add it, or DROP COLUMN below
-- destroys it.
SELECT COUNT(*) AS `unmapped_rows_must_be_zero` FROM `engine_module_zxrelease_hw_required` WHERE `hardwareId` = 0;

ALTER TABLE `engine_module_zxrelease_hw_required`
    DROP KEY `elementId`,
    DROP COLUMN `value`,
    ADD UNIQUE KEY `elementId` (`elementId`, `hardwareId`),
    ADD KEY `hardwareId` (`hardwareId`),
    ADD CONSTRAINT `zxrelease_hw_hardware` FOREIGN KEY (`hardwareId`) REFERENCES `engine_hardware` (`id`);

-- Step 4: privilege ------------------------------------------------------------
-- `editHardware` on the public root for the catalogue managers group: the
-- hardware list is catalogue upkeep, and that group is who maintains it.
--
-- Two notes for whoever revisits this:
--  * privilegesManager reads $user->privileges from the session, so a user who is
--    logged in when this runs only sees the new section after re-logging in;
--  * the privilege only resolves for users who may `show` the public root, which
--    in practice means membership in `public_visitors` — every real account has it.
INSERT INTO `engine_privilege_relations` (`privilegeId`, `elementId`, `type`, `userId`, `module`, `action`)
SELECT 0, `root`.`id`, 1, `grp`.`id`, 'root', 'editHardware'
FROM `engine_structure_elements` `root`
         JOIN `engine_structure_elements` `grp`
              ON `grp`.`structureType` = 'userGroup' AND `grp`.`structureName` = 'catalogues-managers'
WHERE `root`.`marker` = 'public_root'
  AND NOT EXISTS (SELECT 1
                  FROM (SELECT * FROM `engine_privilege_relations`) `existing`
                  WHERE `existing`.`userId` = `grp`.`id`
                    AND `existing`.`elementId` = `root`.`id`
                    AND `existing`.`module` = 'root'
                    AND `existing`.`action` = 'editHardware');
