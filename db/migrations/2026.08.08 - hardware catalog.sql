-- Hardware catalog: move the hardware list out of the `value` ENUM into its own
-- table with localized names, and normalize the release link table to ids.
--
-- Step 0 is mandatory and must run first: the ENUM lists 'aymouse' twice, and
-- MariaDB refuses ANY rebuild of the column while that is true (ERROR 1291) --
-- including ADD COLUMN, ENGINE=InnoDB, CREATE TABLE ... LIKE and mysqldump
-- reload. Rewriting the column definition as VARCHAR drops the duplicate.
--
-- After this migration `value` no longer exists; hardware is referenced by
-- `hardwareId`. Codes remain the contract everywhere above the database
-- (element properties, forms, REST DTOs, the public /api/ filters).

-- Step 0 --------------------------------------------------------------------
ALTER TABLE `engine_module_zxrelease_hw_required` MODIFY `value` VARCHAR(32) NOT NULL;

-- Step 1: clean the link table ----------------------------------------------
-- rows whose release no longer exists (3638 at the time of writing)
DELETE `l` FROM `engine_module_zxrelease_hw_required` `l`
    LEFT JOIN `engine_module_zxrelease` `r` ON `r`.`id` = `l`.`elementId`
WHERE `r`.`id` IS NULL;

-- duplicate (elementId, value) pairs (189), keeping the lowest id of each
DELETE `a` FROM `engine_module_zxrelease_hw_required` `a`
    JOIN `engine_module_zxrelease_hw_required` `b`
        ON `b`.`elementId` = `a`.`elementId` AND `b`.`value` = `a`.`value` AND `b`.`id` < `a`.`id`;

-- Step 2: the catalog --------------------------------------------------------
CREATE TABLE `engine_hardware`
(
    `id`       INT UNSIGNED                                                                  NOT NULL AUTO_INCREMENT,
    `code`     VARCHAR(32)                                                                   NOT NULL,
    `category` ENUM ('computers','storage','dos','sound','controls','expansion')             NOT NULL,
    `position` INT                                                                           NOT NULL DEFAULT 0,
    PRIMARY KEY (`id`),
    UNIQUE KEY `code` (`code`),
    KEY `category` (`category`, `position`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

CREATE TABLE `engine_hardware_name`
(
    `hardwareId`   INT UNSIGNED NOT NULL,
    `languageCode` CHAR(2)      NOT NULL,
    `name`         VARCHAR(255) NOT NULL,
    `shortName`    VARCHAR(255) NOT NULL,
    PRIMARY KEY (`hardwareId`, `languageCode`),
    CONSTRAINT `hardware_name_hardware` FOREIGN KEY (`hardwareId`) REFERENCES `engine_hardware` (`id`) ON DELETE CASCADE
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

